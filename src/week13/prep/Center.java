package week13.prep;

public class Center {
    public int x;
    public int y;
    public Center(int x, int y) {
        this.x = x;
        this.y = y;
    }
    @Override
    public String toString() {
        return "Center{" +
                "x=" + x +
                ", y=" + y +
                '}';
    }

}
